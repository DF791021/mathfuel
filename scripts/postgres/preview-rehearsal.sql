-- Run with psql -X -v ON_ERROR_STOP=1 -f preview-rehearsal.sql on a disposable database.
-- Everything is fictional and the enclosing transaction is rolled back.
BEGIN;
SET LOCAL TIME ZONE 'UTC';
CREATE SCHEMA mathfuel_migration_rehearsal;
REVOKE ALL ON SCHEMA mathfuel_migration_rehearsal FROM PUBLIC;
SET LOCAL search_path TO mathfuel_migration_rehearsal, pg_catalog;

CREATE TABLE users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "openId" varchar(64) NOT NULL UNIQUE,
  "userType" text NOT NULL CHECK ("userType" IN ('student', 'parent', 'teacher', 'admin'))
);

CREATE TABLE "parentStudentLinks" (
  "parentId" integer NOT NULL REFERENCES users(id),
  "studentId" integer NOT NULL REFERENCES users(id),
  PRIMARY KEY ("parentId", "studentId")
);

CREATE TABLE "practiceSessions" (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "studentId" integer NOT NULL REFERENCES users(id),
  "correctAnswers" integer NOT NULL CHECK ("correctAnswers" >= 0),
  "skillsFocused" jsonb,
  "startedAt" timestamptz NOT NULL
);

-- Preserve source IDs and instants during import, then advance the identity.
INSERT INTO users (id, "openId", "userType") VALUES
  (10, 'fictional-student', 'student'),
  (20, 'fictional-linked-parent', 'parent'),
  (30, 'fictional-unlinked-parent', 'parent');
ALTER TABLE users ALTER COLUMN id RESTART WITH 31;
INSERT INTO users ("openId", "userType") VALUES ('fictional-new-student', 'student');

INSERT INTO "parentStudentLinks" VALUES (20, 10);
INSERT INTO "practiceSessions" (id, "studentId", "correctAnswers", "skillsFocused", "startedAt")
VALUES (90, 10, 4, '[2, 3]', '2026-11-21 23:45:00-06');
ALTER TABLE "practiceSessions" ALTER COLUMN id RESTART WITH 91;

DO $$
DECLARE
  parent integer;
  visible_sessions integer;
BEGIN
  IF (SELECT id FROM users WHERE "openId" = 'fictional-new-student') IS DISTINCT FROM 31 THEN
    RAISE EXCEPTION 'Identity did not advance past imported IDs';
  END IF;

  FOREACH parent IN ARRAY ARRAY[20, 30] LOOP
    SELECT COUNT(*) INTO visible_sessions
    FROM "parentStudentLinks" AS link
    JOIN "practiceSessions" AS session ON session."studentId" = link."studentId"
    WHERE link."parentId" = parent AND session.id = 90;
    IF visible_sessions <> (CASE WHEN parent = 20 THEN 1 ELSE 0 END) THEN
      RAISE EXCEPTION 'Parent-to-session join returned unexpected results';
    END IF;
  END LOOP;

  IF NOT EXISTS (
    SELECT 1 FROM "practiceSessions"
    WHERE id = 90 AND "correctAnswers" = 4 AND "skillsFocused" = '[2, 3]'::jsonb
      AND "startedAt" = '2026-11-22 05:45:00+00'::timestamptz
  ) THEN
    RAISE EXCEPTION 'Practice data lost value or timestamp fidelity';
  END IF;

  BEGIN
    INSERT INTO "parentStudentLinks" VALUES (20, 999);
    RAISE EXCEPTION 'Orphan link was accepted';
  EXCEPTION WHEN foreign_key_violation THEN
    NULL;
  END;

  BEGIN
    INSERT INTO "parentStudentLinks" VALUES (20, 10);
    RAISE EXCEPTION 'Duplicate link was accepted';
  EXCEPTION WHEN unique_violation THEN
    NULL;
  END;

  IF EXISTS (
    SELECT 1 FROM pg_roles
    WHERE rolname IN ('anon', 'authenticated')
      AND has_schema_privilege(oid, 'mathfuel_migration_rehearsal', 'USAGE')
  ) THEN
    RAISE EXCEPTION 'A Supabase browser role can use the rehearsal schema';
  END IF;
END;
$$;
ROLLBACK;
